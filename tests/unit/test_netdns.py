"""Tests for daemon.netdns (the network's own DNS servers)."""

import socket

import pytest

from blockads_linux.daemon.netdns import is_local_address, network_upstreams, parse_resolv_conf


def test_parse_resolv_conf():
    text = """# Generated by NetworkManager
search lan
nameserver 192.168.1.1
nameserver 192.168.1.1
nameserver fe80::1%wlan0
nameserver not-an-ip
options edns0 trust-ad
nameserver
 nameserver 10.0.0.1
"""
    assert parse_resolv_conf(text) == ["192.168.1.1", "fe80::1%wlan0", "10.0.0.1"]


@pytest.mark.parametrize("address", ["127.0.0.53", "127.0.0.1", "::1", "0.0.0.0", "::", "224.0.0.251"])
def test_loopback_and_special_addresses_are_local(address):
    assert is_local_address(address)


def test_foreign_and_own_addresses():
    assert not is_local_address("192.0.2.53")  # TEST-NET-1 is never assigned
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.connect(("192.0.2.1", 9))  # no packet is sent; picks our source address
        own = probe.getsockname()[0]
    except OSError:
        pytest.skip("no IPv4 route")
    finally:
        probe.close()
    assert is_local_address(own)


def test_network_upstreams(tmp_path):
    resolv = tmp_path / "resolv.conf"
    resolv.write_text("nameserver 127.0.0.53\n" + "".join(f"nameserver 192.0.2.{i}\n" for i in range(1, 6)))
    assert [s.address for s in network_upstreams(resolv)] == ["192.0.2.1", "192.0.2.2", "192.0.2.3"]
    assert network_upstreams(tmp_path / "missing") == []
